<?php

namespace App\Notifications;

use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Notifications\Messages\MailMessage;
use Illuminate\Notifications\Notification;

class ResetPasswordNotification extends Notification
{
    public $token;

    public function __construct($token)
    {
        $this->token = $token;
    }

    public function via($notifiable)
    {
        return ['mail'];
    }

    public function toMail($notifiable)
    {
        // Link menuju halaman reset password
        $url = url(route('password.reset', [
            'token' => $this->token,
            'email' => $notifiable->getEmailForPasswordReset(),
        ], false));

        return (new MailMessage)
            ->subject('Reset Your Password - eMindTutor')
            ->greeting('Hi ' . $notifiable->name . ',')
            ->line('We received a request to reset the password for your eMindTutor account.')
            ->line('If you did not make this request, please ignore this email. Otherwise, you can reset your password using the button below:')
            ->action('Reset Password', $url)
            ->line('This password reset link will expire in 60 minutes.')
            ->line('Thank you for using our platform!')
            ->salutation('Best Regards, eMindTutor Support Team');
    }
